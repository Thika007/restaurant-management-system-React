BEGIN TRAN;


UPDATE iph
SET iph.price = pf.oldPrice, iph.changedAt = GETDATE()
FROM ItemPriceHistory iph
INNER JOIN #PriceFix pf ON iph.itemCode = pf.itemCode
WHERE iph.effectiveFrom = '2000-01-01' AND pf.oldPrice != pf.currentPrice;


INSERT INTO ItemPriceHistory (itemCode, price, effectiveFrom, changedAt)
SELECT pf.itemCode, pf.currentPrice, @NewPriceEffectiveDate, GETDATE()
FROM #PriceFix pf
WHERE pf.oldPrice != pf.currentPrice
  AND NOT EXISTS (
      SELECT 1 FROM ItemPriceHistory iph2 
      WHERE iph2.itemCode = pf.itemCode AND iph2.effectiveFrom > '2000-01-01'
  );

